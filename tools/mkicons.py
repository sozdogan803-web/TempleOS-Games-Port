"""Windows icons for the translated games, from TempleOS's own sprites.

  mkicons.py gen  <code_root> <bin_root> <out.HC> <game.HC ...>
      Picks each game's sprite -- its icon in PersonalMenu.DD, else the first sprite
      in the game's source -- and writes IconGen.HC, a HolyC program that draws each
      one with Sprite3 and saves it (TosIconSave, C runtime) as <name>.raw.
  mkicons.py ico  <raw_dir>
      Turns every <name>.raw into <name>.ico (16..256 px, transparent background).
  mkicons.py pack <out.ico> <png per size in SIZES order>
      For games with no sprite at all: an icon from pictures of the game's screen.
"""
import os, re, sys, struct, zlib
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hc_lex import split_doc
from hc_build import game_name

TRANSPARENT = 0xFF
PALETTE = [(0x00, 0x00, 0x00), (0x00, 0x00, 0xAA), (0x00, 0xAA, 0x00), (0x00, 0xAA, 0xAA),
           (0xAA, 0x00, 0x00), (0xAA, 0x00, 0xAA), (0xAA, 0x55, 0x00), (0xAA, 0xAA, 0xAA),
           (0x55, 0x55, 0x55), (0x55, 0x55, 0xFF), (0x55, 0xFF, 0x55), (0x55, 0xFF, 0xFF),
           (0xFF, 0x55, 0x55), (0xFF, 0x55, 0xFF), (0xFF, 0xFF, 0x55), (0xFF, 0xFF, 0xFF)]
SIZES = (16, 24, 32, 48, 64, 256)

def bins_of(code_root, bin_root, rel):
    _, bins = split_doc(open(os.path.join(code_root, rel), 'rb').read())
    bp = os.path.join(bin_root, rel)
    if os.path.exists(bp):
        _, bins = split_doc(open(bp, 'rb').read())
    return bins

def menu_icons(code_root, bin_root):
    """game name -> sprite bytes, from the $SP icons of PersonalMenu.DD.
    Text and bins come from the same copy: TinkerOS renumbered its menu's BI= entries, and the
    converted TempleOS copies lost their bins."""
    root = bin_root if os.path.exists(os.path.join(bin_root, 'PersonalMenu.DD')) else code_root
    text, bins = split_doc(open(os.path.join(root, 'PersonalMenu.DD'), 'rb').read())
    out = {}
    for m in re.finditer(r'\$SP[^$]*?LM="#include \\"::/([^"\\]+)\\"[^$]*?BI=(\d+)\$', text):
        path = re.sub(r'(\.HC)?(\.Z)?$', '', m.group(1))
        out.setdefault(game_name(path + '.HC'), bins.get(int(m.group(2))))
    return out

def gen(code_root, bin_root, out_hc, games):
    menu = menu_icons(code_root, bin_root)
    picks = []
    for g in games:
        name = game_name(g)
        spr = menu.get(name)
        if not spr:   # the first sprite in the game's file, else in the file named after its folder (Apps/X/X.HC)
            d = os.path.dirname(g)
            for f in (g, '%s/%s.HC' % (d, os.path.basename(d))):
                bins = bins_of(code_root, bin_root, f) if os.path.exists(os.path.join(code_root, f)) else None
                spr = bins[min(bins)] if bins else None
                if spr: break
        if spr:
            picks.append((name, spr))
        else:
            print('no sprite for', name)
    hc = ['//Generated by mkicons.py: draws each game\'s icon sprite and saves it.',
          'extern U0 TosIconSave(CDC *dc,U8 *name);', '']
    for i, (name, spr) in enumerate(picks):
        hc.append('U8 tos_icon%d[%d]={%s};' % (i, len(spr), ','.join(str(b) for b in spr)))
    hc += ['', 'U0 IconGen()', '{', '  I64 x1,x2,y1,y2;', '  CDC *dc;']
    for i, (name, spr) in enumerate(picks):
        hc += ['  SpriteExtents(tos_icon%d,&x1,&x2,&y1,&y2);' % i,
               '  dc=DCNew(x2-x1+1,y2-y1+1);', '  DCFill(dc,TRANSPARENT);',
               '  Sprite3(dc,-x1,-y1,0,tos_icon%d);' % i,
               '  TosIconSave(dc,"%s");' % name, '  DCDel(dc);']
    hc += ['}', 'IconGen;', '']
    open(out_hc, 'w').write('\n'.join(hc))
    print('%d icons -> %s' % (len(picks), out_hc))

def png(w, h, rgba):
    def chunk(t, d):
        return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xFFFFFFFF)
    rows = b''.join(b'\0' + rgba[y * w * 4:(y + 1) * w * 4] for y in range(h))
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0)) +
            chunk(b'IDAT', zlib.compress(rows, 9)) + chunk(b'IEND', b''))

def square(w, h, px, size):
    """Sprite pixels scaled (nearest, whole factor when it fits) and centred on size x size RGBA."""
    f = size / max(w, h)
    if f >= 1:
        f = int(f)
    sw, sh = max(1, int(w * f)), max(1, int(h * f))
    ox, oy = (size - sw) // 2, (size - sh) // 2
    out = bytearray(size * size * 4)
    for y in range(sh):
        sy = min(h - 1, int(y / f))
        for x in range(sw):
            c = px[sy * w + min(w - 1, int(x / f))]
            if c != TRANSPARENT:
                r, g, b = PALETTE[c & 15]
                o = ((oy + y) * size + ox + x) * 4
                out[o:o + 4] = bytes((r, g, b, 255))
    return bytes(out)

def ico(raw_path, ico_path):
    d = open(raw_path, 'rb').read()
    w, h = struct.unpack_from('<ii', d)
    px = d[8:8 + w * h]
    pack_ico([png(s, s, square(w, h, px, s)) for s in SIZES], ico_path)

def pack_ico(imgs, ico_path):
    """imgs: PNG files' bytes, one per entry of SIZES"""
    head = struct.pack('<HHH', 0, 1, len(imgs))
    off = 6 + 16 * len(imgs)
    dirs = b''
    for s, im in zip(SIZES, imgs):
        dirs += struct.pack('<BBBBHHII', s % 256, s % 256, 0, 0, 1, 32, len(im), off)
        off += len(im)
    open(ico_path, 'wb').write(head + dirs + b''.join(imgs))

def self_check():
    px = bytes([TRANSPARENT, 15, 4, TRANSPARENT])   # 2x2: white and red on the diagonal-ish
    s = square(2, 2, px, 4)
    assert s[3] == 0 and s[(0 * 4 + 2) * 4:(0 * 4 + 2) * 4 + 4] == bytes((255, 255, 255, 255))
    assert png(1, 1, b'\0\0\0\0').startswith(b'\x89PNG')

if __name__ == '__main__':
    self_check()
    if sys.argv[1] == 'gen':
        gen(sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5:])
    elif sys.argv[1] == 'pack':   # pack <out.ico> <16.png> <24.png> ... <256.png>
        pack_ico([open(f, 'rb').read() for f in sys.argv[3:]], sys.argv[2])
    else:
        d = sys.argv[2]
        for f in sorted(os.listdir(d)):
            if f.endswith('.raw'):
                ico(os.path.join(d, f), os.path.join(d, f[:-4] + '.ico'))
                print(f[:-4] + '.ico')
